-- The AI models the chat uses, set by admins on the Usage page (migration
-- chat_models). Only free models (an id ending in :free, or the free router) can
-- be saved, so the chat can't spend the OpenRouter credit. With nothing saved,
-- the chat uses OPENROUTER_MODEL, or the free router.
create function public.chat_models() returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce((select value from public.app_settings where key = 'chat_models'), '{}'::jsonb);
$$;
revoke execute on function public.chat_models() from public, anon;
grant execute on function public.chat_models() to authenticated;

create function public.admin_set_chat_models(main_model text, fallback_model text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  free_model constant text := '^(openrouter/free|[A-Za-z0-9._-]+/[A-Za-z0-9._:-]+:free)$';
begin
  if not public.is_admin() then
    raise exception 'Only admins can change the AI models.' using errcode = '42501';
  end if;
  if main_model is null or fallback_model is null or main_model !~ free_model or fallback_model !~ free_model then
    raise exception 'Only free models can be used.' using errcode = '22023';
  end if;
  insert into public.app_settings (key, value)
  values ('chat_models', jsonb_build_object('main', main_model, 'fallback', fallback_model))
  on conflict (key) do update set value = excluded.value, updated_at = now();
end;
$$;
revoke execute on function public.admin_set_chat_models(text, text) from public, anon;
grant execute on function public.admin_set_chat_models(text, text) to authenticated;

