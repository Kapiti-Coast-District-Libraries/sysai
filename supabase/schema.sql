-- Cached guides (migration kb_cache). SOP-Fetch builds the LibSysAIKB guide list once per
-- commit and keeps it gzipped in the private knowledge-base bucket, instead of unzipping
-- the repo on every page load. Only the service role (the function) can use either.
create table public.kb_cache (
  id smallint primary key default 1 check (id = 1),
  sha text,                    -- the LibSysAIKB commit the copy was built from
  build integer,               -- BUILD in SOP-Fetch/kb.ts when it was built
  path text,                   -- the copy's name in the knowledge-base bucket
  files integer,
  built_at timestamptz,
  checked_at timestamptz,      -- when GitHub was last asked for the latest commit
  refreshing_since timestamptz -- set while one page load is checking or rebuilding
);
insert into public.kb_cache (id) values (1);
alter table public.kb_cache enable row level security;
revoke all on table public.kb_cache from anon, authenticated;

-- True for the one page load that should check GitHub now: the copy is missing or hasn't
-- been checked for check_every, and nobody else has been refreshing it for lock_for.
create function public.claim_kb_refresh(check_every interval, lock_for interval)
returns boolean
language sql
set search_path = ''
as $$
  with claimed as (
    update public.kb_cache
    set refreshing_since = now()
    where id = 1
      and (path is null or checked_at is null or checked_at < now() - check_every)
      and (refreshing_since is null or refreshing_since < now() - lock_for)
    returning 1
  )
  select exists (select 1 from claimed);
$$;
revoke execute on function public.claim_kb_refresh(interval, interval) from public, anon, authenticated;
grant execute on function public.claim_kb_refresh(interval, interval) to service_role;

