-- Questions per person per day. Only log_rpd writes to it.
create table public."Useage" (
  id bigint generated by default as identity primary key,
  "User Account" uuid not null default auth.uid() references auth.users (id) on update cascade,
  "RPD" bigint,
  "Date" date,
  "Email Address" character varying,
  constraint user_date_unique unique ("User Account", "Date")
);
alter table public."Useage" enable row level security;
revoke all on table public."Useage" from anon, authenticated;

-- Logs one question for the signed-in caller. Keeps the uid parameter the site
-- sends but ignores it, so nobody can log questions against someone else.
create function public.log_rpd(uid uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    return;
  end if;
  insert into public."Useage" ("User Account", "Date", "RPD")
  values (auth.uid(), current_date, 1)
  on conflict ("User Account", "Date")
  do update set "RPD" = public."Useage"."RPD" + 1;
end;
$$;
revoke execute on function public.log_rpd(uuid) from public, anon;
grant execute on function public.log_rpd(uuid) to authenticated;

