  updated_at timestamptz not null default now()
);
alter table public.app_settings enable row level security;
revoke all on table public.app_settings from anon, authenticated;

create table public.request_limits (
  user_id uuid primary key references auth.users (id) on delete cascade,
  daily_limit integer not null check (daily_limit >= 0),
  updated_at timestamptz not null default now()
);
alter table public.request_limits enable row level security;
revoke all on table public.request_limits from anon, authenticated;

create function public.questions_today(target uuid) returns integer
language sql stable security definer set search_path = '' as $$
  select count(*)::integer from public.model_usage
  where user_id = target and error is null
    and (created_at at time zone 'Pacific/Auckland')::date = (now() at time zone 'Pacific/Auckland')::date;
$$;

create function public.effective_limit(target uuid) returns integer
language sql stable security definer set search_path = '' as $$
  select coalesce(
    (select daily_limit from public.request_limits where user_id = target),
    (select (value ->> 'daily_limit')::integer from public.app_settings where key = 'default_daily_limit'));
$$;

revoke execute on function public.questions_today(uuid), public.effective_limit(uuid) from public, anon, authenticated;

-- Called by the libsys-chat function before each question.
create function public.request_allowance() returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'used', public.questions_today(auth.uid()),
    'limit', public.effective_limit(auth.uid()),
    'allowed', auth.uid() is not null
      and (public.effective_limit(auth.uid()) is null
           or public.questions_today(auth.uid()) < public.effective_limit(auth.uid())));
$$;

